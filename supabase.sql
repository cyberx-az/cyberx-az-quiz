-- Supabase SQL Editor-də bu kodu icra et.
create table if not exists public.quiz_results (
  id bigint generated by default as identity primary key,
  participant_name text not null check (char_length(participant_name) between 1 and 50),
  correct_answers integer not null check (correct_answers between 0 and 10),
  wrong_answers integer not null check (wrong_answers between 0 and 10),
  score integer not null check (score between 0 and 100),
  created_at timestamptz not null default now()
);

alter table public.quiz_results enable row level security;

-- İştirakçılar nəticə əlavə edə bilər, amma siyahını oxuya bilməz.
create policy "Anyone can submit quiz result"
on public.quiz_results for insert
to anon, authenticated
with check (
  char_length(participant_name) between 1 and 50
  and correct_answers between 0 and 10
  and wrong_answers between 0 and 10
  and score between 0 and 100
);

-- Yalnız admin kimi daxil olmuş istifadəçi nəticələri oxuya bilər.
create policy "Authenticated admin can read results"
on public.quiz_results for select
to authenticated
using (auth.uid() is not null);
